void write_float(std::ostream& output, float value) {
    output.write(reinterpret_cast<const char*>(&value), sizeof(value));
}

std::filesystem::path temporary_path_for(const std::filesystem::path& destination) {
    static std::atomic<std::uint64_t> sequence{};
    const auto ticks = std::chrono::steady_clock::now().time_since_epoch().count();
    return destination.parent_path()
        / (destination.filename().string() + ".tmp-" + std::to_string(ticks) + "-"
           + std::to_string(sequence.fetch_add(1)));
}

void commit_temporary_file(
    const std::filesystem::path& temporary,
    const std::filesystem::path& destination
) {
#ifdef _WIN32
    if (MoveFileExW(
            temporary.c_str(),
            destination.c_str(),
            MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH
        ) == 0) {
        const auto error = GetLastError();
        throw std::runtime_error(
            "cannot commit output atomically (Windows error " + std::to_string(error) + "): "
            + destination.string()
        );
    }
#else
    std::error_code error;
    std::filesystem::rename(temporary, destination, error);
    if (error) {
        throw std::runtime_error(
            "cannot commit output atomically: " + destination.string() + ": " + error.message()
        );
    }
#endif
}

template <typename Writer>
void write_atomically(
    const std::filesystem::path& destination,
    std::ios::openmode mode,
    Writer writer
) {
    const auto temporary = temporary_path_for(destination);
    try {
        std::ofstream output(temporary, mode);
        if (!output) {
            throw std::runtime_error("cannot open temporary output: " + temporary.string());
        }
        output.imbue(std::locale::classic());
        writer(output);
        output.flush();
        if (!output) {
            throw std::runtime_error("failed while writing output: " + destination.string());
        }
        output.close();
        if (!output) {
            throw std::runtime_error("failed while closing output: " + destination.string());
        }
        commit_temporary_file(temporary, destination);
    } catch (...) {
        std::error_code ignored;
        std::filesystem::remove(temporary, ignored);
        throw;
    }
}

const char* semantics_name(DepthSemantics semantics) {
    switch (semantics) {
    case DepthSemantics::RelativeInverse:
        return "relative_inverse";
    case DepthSemantics::MetricCameraZ:
        return "metric_camera_z";
    case DepthSemantics::PseudoInverseFromSegmentation:
        return "pseudo_inverse_from_segmentation";
    }
    throw std::invalid_argument("unknown depth semantics");
}

